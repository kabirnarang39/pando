#!/bin/sh
# Regenerate the CLI, server and protocol reference pages from the real binaries and protos.
# Usage: scripts/gen-reference.sh [BIN_DIR]   (BIN_DIR holds `pando` and `pandod`; default: on PATH)
set -eu
root="$(cd "$(dirname "$0")/.." && pwd)"
bin="${1:-}"; [ -n "$bin" ] && bin="${bin%/}/"
out="$root/docs/reference"
mkdir -p "$out"

# Subcommand names listed under "Commands:" in a --help page, without `help`.
subcommands() {
  "$@" --help | awk '/^Commands:/{on=1; next} on && /^$/{exit} on && $1 != "help" {print $1}'
}

# One section per command, recursing into subcommands.
walk() (
  depth="$1"; shift
  hashes=$(printf '%*s' "$depth" '' | tr ' ' '#')
  printf '%s `%s`\n\n```text\n' "$hashes" "$(echo "$*" | sed "s|^$bin||")"
  "$@" --help | sed 's/[[:space:]]*$//'
  printf '```\n\n'
  for sub in $(subcommands "$@"); do walk $((depth + 1)) "$@" "$sub"; done
)

header() {
  printf '# %s\n\n<!-- Generated by scripts/gen-reference.sh from `%s --version`: %s. Do not edit by hand. -->\n\n%s\n\n' \
    "$1" "$2" "$("$bin$2" --version)" "$3"
}

{
  header "CLI reference" pando \
    "Every \`pando\` command and option, as printed by \`--help\`. For a task-by-task guide, start with [Try it in 5 minutes](../getting-started.md); for git equivalents, see [Coming from git](../git-users.md)."
  for c in $(subcommands "${bin}pando"); do walk 2 "${bin}pando" "$c"; done
} > "$out/cli.md"

{
  header "Server reference" pandod \
    "Every \`pandod\` command and option, as printed by \`--help\`. Options listed under \`pandod\` itself apply to every command and go before it (\`pandod --metrics 0.0.0.0:9420 server ...\`). Each option's environment variable is shown in brackets. The most used settings are summarised in [Configuration](configuration.md)."
  printf '## `pandod`\n\n```text\n'; "${bin}pandod" --help | sed 's/[[:space:]]*$//'; printf '```\n\n'
  for c in $(subcommands "${bin}pandod"); do walk 2 "${bin}pandod" "$c"; done
} > "$out/server.md"

# Protocol: every service and RPC with its leading comment, from the .proto files.
{
  printf '# Protocol reference\n\n<!-- Generated by scripts/gen-reference.sh from crates/pando-proto/proto. Do not edit by hand. -->\n\n'
  printf 'Pando speaks gRPC (HTTP/2, and gRPC-Web for browsers). The `pando.v1` package is stable: it changes only by adding. Generate a client for any language from the files below; the [SDKs](../agents.md#sdks) wrap the read calls for Python, TypeScript and Go.\n\n'
  printf 'Calls to a server that hosts many repositories name one with the `x-pando-repo: OWNER/NAME` header. Every call takes a bearer token in `authorization` when the server requires one.\n\n'
  for f in "$root"/crates/pando-proto/proto/pando.proto "$root"/crates/pando-proto/proto/pando_*.proto; do
    grep -q '^service ' "$f" || continue
    name=$(basename "$f")
    printf '## `%s`\n\n[Source](https://github.com/kabirnarang39/pando/blob/main/crates/pando-proto/proto/%s)\n' "$name" "$name"
    awk '
      /^[[:space:]]*\/\// { t = $0; sub(/^[[:space:]]*\/\/+[[:space:]]?/, "", t); c = c (c ? " " : "") t; next }
      /^service / { printf "\n### %s\n\n", $2; if (c) printf "%s\n\n", c; printf "| Call | Request | Response | What it does |\n|---|---|---|---|\n"; c = ""; next }
      /^[[:space:]]*rpc / {
        line = $0; sub(/^[[:space:]]*rpc[[:space:]]+/, "", line)
        n = line; sub(/[[:space:]]*\(.*/, "", n)
        req = line; sub(/^[^(]*\(/, "", req); sub(/\).*/, "", req)
        res = line; sub(/^.*returns[[:space:]]*\(/, "", res); sub(/\).*/, "", res)
        gsub(/\|/, "\\|", c)
        printf "| `%s` | `%s` | `%s` | %s |\n", n, req, res, c; c = ""; next
      }
      { c = "" }
    ' "$f"
    printf '\n'
  done
} > "$out/protocol.md"
echo "wrote $out/cli.md $out/server.md $out/protocol.md"
